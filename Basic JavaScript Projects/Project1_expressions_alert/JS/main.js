//This variable contains the beginning of the string.
var sent1= "This is the beginning of the string";

//This variable contains the end of the string.
var sent2= "And this is the end of the string";

//This expression concatenates the two variables into one string.
var fullSentence= sent1 + " " + sent2;

//This displays the concatenated string in an alert window.
window.alert(fullSentence);

//This writes the concatenated string to the webpage.
document.write(fullSentence);